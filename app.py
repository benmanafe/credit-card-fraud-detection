# --- 1. DEFINE MODEL CLASS ---
class Autoencoder(nn.Module):
    def __init__(self, input_dim):
        super(Autoencoder, self).__init__()
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, 20), nn.Tanh(),
            nn.Linear(20, 14), nn.Tanh(),
            nn.Linear(14, 8), nn.Tanh(),
        )
        self.decoder = nn.Sequential(
            nn.Linear(8, 14), nn.Tanh(),
            nn.Linear(14, 20), nn.Tanh(),
            nn.Linear(20, input_dim),
        )

    def forward(self, x):
        encoded = self.encoder(x)
        decoded = self.decoder(encoded)
        return decoded

# --- 2. LOAD ARTIFACTS ---
@st.cache_resource
def load_artifacts():
    with open('fraud_detector.pth', 'rb') as f:
        artifacts = pickle.load(f)
    
    model = Autoencoder(artifacts['input_dim'])
    model.load_state_dict(artifacts['model_state'])
    model.eval()
    
    return model, artifacts['scaler_amount'], artifacts['scaler_time'], artifacts['threshold'], artifacts['feature_names']

model, scaler_amount, scaler_time, threshold, feature_names = load_artifacts()

# --- 3. PDF GENERATOR FUNCTION ---
def create_pdf_report(total_tx, fraud_count, money_at_risk):
    pdf = FPDF()
    pdf.add_page()
    
    # Title
    pdf.set_font("Arial", 'B', 16)
    pdf.cell(0, 10, "Fraud Detection Summary Report", ln=True, align='C')
    pdf.ln(10)
    
    # Stats
    pdf.set_font("Arial", size=12)
    pdf.cell(0, 10, f"Total Transactions Processed: {total_tx}", ln=True)
    pdf.cell(0, 10, f"Total Fraudulent Transactions Detected: {fraud_count}", ln=True)
    
    percentage = (fraud_count / total_tx) * 100
    pdf.cell(0, 10, f"Fraud Rate: {percentage:.2f}%", ln=True)
    pdf.ln(5)
    
    # Financial Impact
    pdf.set_font("Arial", 'B', 12)
    pdf.set_text_color(194, 24, 7) # Red color
    pdf.cell(0, 10, f"Total Money at Risk: ${money_at_risk:,.2f}", ln=True)
    
    # Disclaimer
    pdf.ln(20)
    pdf.set_text_color(100, 100, 100) # Gray
    pdf.set_font("Arial", 'I', 10)
    pdf.multi_cell(0, 10, "Note: This report is generated by an AI Autoencoder model. Flagged transactions should be verified manually by a fraud analyst.")
    
    return pdf.output(dest='S').encode('latin-1')

