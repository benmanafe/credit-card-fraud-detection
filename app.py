st.title("🛡️ Credit Card Fraud Detector")
st.write("Based on Autoencoder Anomaly Detection")

tab1, tab2 = st.tabs(["📝 Single Transaction", "📂 Batch File Upload"])

# TAB 1: SINGLE TRANSACTION (Unchanged)
with tab1:
    st.sidebar.header("Single Transaction Details")
    user_amount = st.sidebar.number_input("Transaction Amount ($)", min_value=0.0, value=100.0)
    user_time = st.sidebar.number_input("Time (Seconds since start)", min_value=0, value=3600)
    scenario = st.sidebar.selectbox("Simulate Scenario", ["Normal Transaction", "Fraudulent Transaction"])

    if st.button("Analyze Single Transaction"):
        input_data = np.zeros(30)
        if scenario == "Normal Transaction":
            input_data[0:28] = np.random.normal(0, 1.0, 28)
        else:
            input_data[0:28] = np.random.normal(0, 1.0, 28)
            indices = np.random.choice(range(28), 3, replace=False)
            input_data[indices] += np.random.uniform(10, 20, 3) * np.random.choice([-1, 1], 3)

        scaled_amt = scaler_amount.transform([[user_amount]])
        scaled_tm = scaler_time.transform([[user_time]])
        input_data[28] = scaled_amt[0][0]
        input_data[29] = scaled_tm[0][0]
        
        input_tensor = torch.FloatTensor(input_data).unsqueeze(0)
        with torch.no_grad():
            reconstruction = model(input_tensor)
            loss_per_feature = (input_tensor - reconstruction) ** 2
            total_loss = torch.mean(loss_per_feature).item()
        
        col1, col2 = st.columns(2)
        col1.metric("Anomaly Score", f"{total_loss:.4f}")
        col2.metric("Threshold", f"{threshold:.4f}")

        if total_loss > threshold:
            st.error("🚨 FRAUD DETECTED!")
        else:
            st.success("✅ Transaction Normal")

